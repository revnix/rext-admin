/**
 * Zod validation schema for topic scores
 * Used in both frontend and backend topic structures
 */
export const TopicScoresSchema = z.object({
  /** Relevance score (0-100): How well the topic matches user criteria */
  relevance: z.number().min(0).max(100),
  /** Freshness score (0-100): How current/timely the topic is */
  freshness: z.number().min(0).max(100),
  /** Novelty score (0-100): How unique/original the topic approach is */
  novelty: z.number().min(0).max(100),
});

/**
 * Zod validation schema for frontend GeneratedTopic
 * Represents topics as generated by AI and displayed in the UI
 */
export const GeneratedTopicSchema = z.object({
  /** Unique topic identifier (frontend-generated) */
  id: z.string().min(1),
  /** Main topic headline/title */
  title: z.string().min(1).max(200),
  /** Specific angle or approach for the topic */
  angle: z.string().min(1).max(500),
  /** Brief topic description (optional in some flows) */
  description: z.string().optional(),
  /** AI-generated quality scores */
  scores: TopicScoresSchema,
  /** Channels/platforms this topic fits well */
  channel_fit: z.array(z.string()).default([]),
  /** Audience segments this topic appeals to */
  audience_fit: z.array(z.string()).default([]),
  /** Explanation of why this topic works well */
  why_it_works: z.string().min(1),
  /** Categorization tags for the topic */
  tags: z.array(z.string()).default([]),
  /** When the topic was generated (ISO string) */
  generated_at: z.string().datetime().optional(),
  /** Generation metadata */
  metadata: z
    .object({
      /** Original generation request parameters */
      generation_params: z.record(z.string(), z.unknown()).optional(),
      /** AI model used for generation */
      model_used: z.string().optional(),
      /** Generation confidence score */
      confidence: z.number().min(0).max(1).optional(),
    })
    .optional(),
});

/**
 * Zod validation schema for backend SaveTopicItem
 * Represents topics as expected by the save-topic API endpoint
 */
export const SaveTopicItemSchema = z.object({
  /** Topic title/headline (required for backend) */
  title: z.string().min(1).max(200),
  /** Specific angle or approach (required for backend) */
  angle: z.string().min(1).max(500),
  /** Channels/platforms this topic fits well (required for backend) */
  channel_fit: z.array(z.string()).min(1),
  /** Audience segments this topic appeals to (required for backend) */
  audience_fit: z.array(z.string()).min(1),
  /** AI-generated quality scores (required for backend) */
  scores: TopicScoresSchema,
  /** Explanation of why this topic works well (required for backend) */
  why_it_works: z.string().min(1),
  /** Categorization tags for the topic (required for backend) */
  tags: z.array(z.string()).min(1),
});

