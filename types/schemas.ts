/**
 * Transforms a GeneratedTopic to SaveTopicItem format for backend API
 *
 * @param topic - Frontend GeneratedTopic object
 * @returns SaveTopicItem formatted for backend API
 * @throws Error if transformation fails due to missing required fields
 */
export const transformTopicForSaving = (
  topic: GeneratedTopic,
): SaveTopicItem => {
  // Validate input
  if (!isValidGeneratedTopic(topic)) {
    throw new Error("Invalid GeneratedTopic provided for transformation");
  }

  // Ensure required arrays have at least one item
  if (topic.channel_fit.length === 0) {
    throw new Error("channel_fit array cannot be empty for backend save");
  }
  if (topic.audience_fit.length === 0) {
    throw new Error("audience_fit array cannot be empty for backend save");
  }
  if (topic.tags.length === 0) {
    throw new Error("tags array cannot be empty for backend save");
  }

  // Transform to backend format (remove frontend-only fields)
  const backendTopic: SaveTopicItem = {
    title: topic.title,
    angle: topic.angle,
    channel_fit: topic.channel_fit,
    audience_fit: topic.audience_fit,
    scores: topic.scores,
    why_it_works: topic.why_it_works,
    tags: topic.tags,
  };

  // Validate output
  if (!isValidSaveTopicItem(backendTopic)) {
    throw new Error("Transformed topic failed backend validation");
  }

  return backendTopic;
};

/**
 * Transforms multiple GeneratedTopics to SaveTopicItems for bulk saving
 *
 * @param topics - Array of frontend GeneratedTopic objects
 * @returns Array of SaveTopicItem formatted for backend API
 */
export const transformTopicsForSaving = (
  topics: GeneratedTopic[],
): SaveTopicItem[] => {
  return topics.map((topic, index) => {
    try {
      return transformTopicForSaving(topic);
    } catch (error) {
      throw new Error(`Failed to transform topic at index ${index}: ${error}`);
    }
  });
};

/**
 * Adds required timestamp to TopicBuilderFormData for backend API
 *
 * @param formData - Frontend form data
 * @returns Form data with timestamp added
 */
export const prepareFormDataForBackend = (formData: TopicBuilderFormData) => {
  return {
    ...formData,
    timestamp: new Date().toISOString(),
  };
};

