/**
 * Type guard to validate if an object is a valid GeneratedTopic
 */
export const isValidGeneratedTopic = (obj: unknown): obj is GeneratedTopic => {
  try {
    GeneratedTopicSchema.parse(obj);
    return true;
  } catch {
    return false;
  }
};

/**
 * Type guard to validate if an object is a valid SaveTopicItem
 */
export const isValidSaveTopicItem = (obj: unknown): obj is SaveTopicItem => {
  try {
    SaveTopicItemSchema.parse(obj);
    return true;
  } catch {
    return false;
  }
};

/**
 * Type guard to validate if an object is valid TopicBuilderFormData
 */
export const isValidTopicBuilderFormData = (
  obj: unknown,
): obj is TopicBuilderFormData => {
  try {
    TopicBuilderFormDataSchema.parse(obj);
    return true;
  } catch {
    return false;
  }
};

/**
 * Validates an array of topics for backend saving
 */
export const validateTopicsForSaving = (topics: unknown[]): SaveTopicItem[] => {
  return topics.map((topic, index) => {
    try {
      return SaveTopicItemSchema.parse(topic);
    } catch (error) {
      throw new Error(`Topic at index ${index} is invalid: ${error}`);
    }
  });
};

